import path from 'path';
import { ACPClient } from '@/lib/acp';
import {
  createAgentSession,
  getAgentSession,
  updateAgentSessionStatus,
} from '@/lib/db/sessionQueries';
import { getTargetDirectory } from '@/lib/workspace/config';
import {
  handleCreateTicket,
  handleSteerTask,
  handleInspectTask,
  handleManageTicket,
  handleGetBoardStatus,
  handleListWorkspace,
  handleReadWall,
  handlePinToWall,
} from './tools/handlers';
import {
  CreateTicketInputSchema,
  SteerTaskInputSchema,
  InspectTaskInputSchema,
  ManageTicketInputSchema,
  GetBoardStatusInputSchema,
  ListWorkspaceInputSchema,
  ReadWallInputSchema,
  PinToWallInputSchema,
} from './tools/schemas';
import type { ChatMessageRecord } from '@/lib/db/schema';

class OrchestratorSessionManager {
  private client: ACPClient | null = null;
  private sessionId: string | null = null;
  private isInitializing = false;

  // Initialize or retrieve the persistent Orchestrator session in Slot 1
  async ensureSession(): Promise<{ client: ACPClient; sessionId: string }> {
    if (this.client && this.client.isAlive && this.sessionId) {
      return { client: this.client, sessionId: this.sessionId };
    }

    if (this.isInitializing) {
      // Wait for in-flight init
      while (this.isInitializing) {
        await new Promise((r) => setTimeout(r, 100));
      }
      if (this.client && this.sessionId) {
        return { client: this.client, sessionId: this.sessionId };
      }
    }

    this.isInitializing = true;
    try {
      const rootDir = getTargetDirectory();

      this.client = new ACPClient({
        cwd: rootDir,
        env: {
          OPENCODE_DB: path.join(process.cwd(), 'data', '.opencode-orchestrator.db'),
        },
      });

      await this.client.initialize();
      const newSessionId = await this.client.createSession();
      this.sessionId = newSessionId;

      // Persist Orchestrator session in SQLite
      const existing = getAgentSession(newSessionId);
      if (!existing) {
        createAgentSession({
          id: newSessionId,
          ticketId: null,
          role: 'orchestrator',
          worktreeDir: rootDir,
        });
      }

      return { client: this.client, sessionId: this.sessionId };
    } finally {
      this.isInitializing = false;
    }
  }

  // Get active session ID for UI header
  getSessionId(): string | null {
    return this.sessionId;
  }

  // Dispatch tool calls generated by orchestrator
  async executeTool(toolName: string, args: Record<string, any>) {
    switch (toolName) {
      case 'create_ticket':
        return await handleCreateTicket(CreateTicketInputSchema.parse(args));
      case 'steer_task':
        return await handleSteerTask(SteerTaskInputSchema.parse(args));
      case 'inspect_task':
        return await handleInspectTask(InspectTaskInputSchema.parse(args));
      case 'manage_ticket':
        return await handleManageTicket(ManageTicketInputSchema.parse(args));
      case 'get_board_status':
        return await handleGetBoardStatus(GetBoardStatusInputSchema.parse(args));
      case 'list_workspace':
        return await handleListWorkspace(ListWorkspaceInputSchema.parse(args));
      case 'read_wall':
        return await handleReadWall(ReadWallInputSchema.parse(args));
      case 'pin_to_wall':
        return await handlePinToWall(PinToWallInputSchema.parse(args), 'orchestrator');
      default:
        throw new Error(`Unknown tool: ${toolName}`);
    }
  }

  destroy(): void {
    if (this.sessionId) {
      updateAgentSessionStatus(this.sessionId, 'completed');
    }
    if (this.client) {
      this.client.destroy();
      this.client = null;
      this.sessionId = null;
    }
  }
}

// Global singleton to survive Next.js HMR reloads
const globalForOrchestrator = global as unknown as { factoryOrchestratorSession?: OrchestratorSessionManager };
export const orchestratorSessionManager =
  globalForOrchestrator.factoryOrchestratorSession ?? new OrchestratorSessionManager();
if (process.env.NODE_ENV !== 'production') {
  globalForOrchestrator.factoryOrchestratorSession = orchestratorSessionManager;
}
